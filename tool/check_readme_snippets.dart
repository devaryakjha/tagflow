// Checks that the Dart snippets in the READMEs compile.
//
// Usage, from the repository root: dart run tool/check_readme_snippets.dart
//
// Each ```dart block becomes a file in a temporary folder inside the example
// app, which depends on both packages, and `dart analyze` checks it. A block
// that declares a class is used as a whole file;
// any other block becomes the body of a function, with placeholder values
// for the names the READMEs leave to the reader (`htmlContent`, `answer`,
// `document` and so on). Put `<!-- readme-snippet: skip -->` on the line
// before a block that is not Dart code.
import 'dart:io';

const _readmes = [
  'README.md',
  'packages/tagflow/README.md',
  'packages/tagflow_table/README.md',
];

const _skipMarker = '<!-- readme-snippet: skip -->';

const _prelude = '''
// Generated by tool/check_readme_snippets.dart.
// ignore_for_file: type=lint, deprecated_member_use, unused_import
import 'package:flutter/material.dart';
import 'package:tagflow/legacy.dart';
import 'package:tagflow/tagflow.dart';
import 'package:tagflow_table/tagflow_table.dart';
''';

const _placeholders = r'''
const htmlContent = '<p>Hello</p>';
const html = htmlContent;
const articleContent = htmlContent;
const answer = '# Hello';
const Map<String, Object?> nativeJson = {};
final document = TagflowDocument(id: 'doc', children: const []);
const codec = TagflowNativeBlockCodec();
const adapter = TagflowNativeBlockAdapter();
const theme = TagflowTheme.raw(styles: {}, defaultStyle: TagflowStyle());
final myHighlighter = _Highlighter();

final class _Highlighter {
  List<InlineSpan> highlight(String source) => [TextSpan(text: source)];
}
''';

Future<void> main() async {
  final root = Directory.current;
  final output = Directory(
    '${root.path}/examples/tagflow/lib/_readme_snippets',
  );
  if (output.existsSync()) output.deleteSync(recursive: true);
  output.createSync(recursive: true);

  final sources = <String, String>{};
  try {
    for (final readme in _readmes) {
      final lines = File('${root.path}/$readme').readAsLinesSync();
      var index = 0;
      for (var i = 0; i < lines.length; i++) {
        if (lines[i].trim() != '```dart') continue;
        final skip = i > 0 && lines[i - 1].trim() == _skipMarker;
        final body = <String>[];
        for (i++; i < lines.length && lines[i].trim() != '```'; i++) {
          body.add(lines[i]);
        }
        index++;
        if (skip) continue;
        final slug = readme.toLowerCase().replaceAll(RegExp('[^a-z]+'), '_');
        final name = 'snippet_${slug}_$index.dart';
        final file = File('${output.path}/$name');
        file.writeAsStringSync(_wrap(body));
        sources[name] = '$readme, Dart block $index';
      }
    }

    final result = await Process.run('dart', [
      'analyze',
      '--no-fatal-warnings',
      output.path,
    ], workingDirectory: '${root.path}/examples/tagflow');
    final problems = '${result.stdout}'
        .split('\n')
        // Only errors: the wrapping makes unused-variable warnings expected.
        .where((line) => line.contains('error -'))
        .toList();
    if (problems.isEmpty) {
      stdout.writeln('All ${sources.length} README snippets compile.');
      return;
    }
    for (final problem in problems) {
      final name = sources.keys.firstWhere(
        (name) => problem.contains('$name:'),
        orElse: () => '',
      );
      stderr.writeln('${sources[name] ?? ''}: ${problem.trim()}');
    }
    exitCode = 1;
  } finally {
    if (output.existsSync()) output.deleteSync(recursive: true);
  }
}

String _wrap(List<String> body) {
  final imports = body.where((line) => line.startsWith('import ')).toList();
  final rest = body.where((line) => !line.startsWith('import ')).toList();
  final topLevel = rest.any(
    (line) => RegExp(r'^(final |abstract |)class ').hasMatch(line),
  );
  final buffer = StringBuffer(_prelude)
    ..writeAll(imports, '\n')
    ..writeln()
    ..writeln(_placeholders);
  if (topLevel) {
    buffer.writeAll(rest, '\n');
  } else {
    buffer
      ..writeln('void snippet(BuildContext context, Widget child) {')
      ..writeAll(rest.map((line) => '  $line'), '\n')
      ..writeln('\n}');
  }
  return '$buffer\n';
}
